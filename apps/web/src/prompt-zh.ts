/** Translate a comma-separated tag prompt; unknown tags stay as written. */
export function translatePrompt(prompt: string): string {
  return prompt.split(',').map(tag => tag.trim()).filter(Boolean)
    .map(tag => TAG_ZH[tag.toLowerCase()] ?? tag).join('，')
}
